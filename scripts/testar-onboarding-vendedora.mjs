import {createRequire} from 'node:module';
import {readFileSync, mkdirSync} from 'node:fs';
import {pathToFileURL, fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const {chromium} = createRequire(import.meta.url)(process.env.A24_PLAYWRIGHT_PATH || 'playwright');
const browser = await chromium.launch({headless:true,channel:'msedge'});
try {
  const page = await browser.newPage({viewport:{width:390,height:844}, acceptDownloads:true});
  const errors=[];
  page.on('pageerror', e=>{errors.push(e.message);console.error(e.message);});
  const root = new URL('../',import.meta.url);
  await page.goto(pathToFileURL(fileURLToPath(new URL('vendedora.html',root))).href);
  assert.equal(await page.locator('#f-codigo').count(),0);
  assert.equal(await page.locator('#brand-logo').evaluate(el=>el.naturalWidth>0),true);
  await page.locator('#f-nome').fill('Salão Teste Comercial');
  await page.locator('#btn-next').click();
  assert.equal(await page.evaluate(()=>currentStep),0, 'Etapa incompleta deve indicar pendência');
  const draft = await page.evaluate(()=>JSON.stringify(makeDraft()));
  const principal=await browser.newPage();
  await principal.goto(pathToFileURL(fileURLToPath(new URL('index.html',root))).href);
  assert.equal(await principal.evaluate(text=>parseDraft(text).empresa.nome_fantasia,draft),'Salão Teste Comercial');
  const returned=await principal.evaluate(text=>{state=parseDraft(text);state.empresa.observacoes='Revisado pelo responsável';return JSON.stringify(makeDraft());},draft);
  assert.equal(await page.evaluate(text=>parseDraft(text).empresa.observacoes,returned),'Revisado pelo responsável');
  await page.evaluate(()=>goToStep(5));
  assert.equal(await page.locator('#provisionamento-chave, #btn-generate-contract, .json-preview').count(),0);
  assert.equal(await page.locator('#commercial-share').count(),1);
  // Simula somente a integração do navegador; não envia mensagens a contatos reais.
  await page.evaluate(() => {
    window.sharedDrafts = [];
    Object.defineProperty(navigator, 'canShare', {configurable: true, value: () => true});
    Object.defineProperty(navigator, 'share', {configurable: true, value: async data => {
      window.sharedDrafts.push(JSON.parse(await data.files[0].text()));
    }});
  });
  await page.locator('#btn-share-draft').click();
  await page.waitForFunction(()=>sharedDrafts.length===1);
  assert.equal(await page.evaluate(()=>sharedDrafts[0].dados.empresa.nome_fantasia),'Salão Teste Comercial');
  await page.evaluate(()=>{state.empresa.nome_fantasia='Segundo Cliente';});
  await page.locator('#btn-share-draft').click();
  await page.waitForFunction(()=>sharedDrafts.length===2);
  assert.equal(await page.evaluate(()=>sharedDrafts[1].dados.empresa.nome_fantasia),'Segundo Cliente');
  await page.evaluate(()=>{state.empresa.nome_fantasia='Salão Teste Comercial';});
  await page.locator('#commercial-share').isDisabled().then(disabled=>assert.equal(disabled,true));
  let accidentalDownloads = 0;
  page.on('download',()=>accidentalDownloads++);
  await page.evaluate(()=>Object.defineProperty(navigator,'canShare',{configurable:true,value:()=>false}));
  await page.locator('#btn-share-draft').click();
  assert.match(await page.locator('#file-status').innerText(),/não permite compartilhar/);
  assert.equal(accidentalDownloads,0);
  await page.evaluate(()=>{
    Object.defineProperty(navigator,'canShare',{configurable:true,value:()=>true});
    Object.defineProperty(navigator,'share',{configurable:true,value:async()=>{throw new DOMException('Cancelado','AbortError');}});
  });
  await page.locator('#btn-share-draft').click();
  assert.match(await page.locator('#file-status').innerText(),/cancelado/);
  assert.equal(accidentalDownloads,0);
  const downloadEvent=page.waitForEvent('download');
  await page.locator('#btn-save-draft').click();
  const downloaded=await downloadEvent;
  const saved=JSON.parse(readFileSync(await downloaded.path(),'utf8'));
  assert.equal(saved.tipo_arquivo,'agenda24h-rascunho');
  assert.equal(saved.dados.empresa.nome_fantasia,'Salão Teste Comercial');
  await page.waitForTimeout(600);
  await page.reload();
  await page.getByRole('button',{name:'Recuperar último preenchimento'}).click();
  await page.getByRole('button',{name:'Recuperar',exact:true}).click();
  assert.equal(await page.evaluate(()=>state.empresa.nome_fantasia),'Salão Teste Comercial');
  await page.evaluate(()=>goToStep(0));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  const out=new URL('../output/onboarding-vendedora/',import.meta.url);
  mkdirSync(out,{recursive:true});
  await page.screenshot({path:fileURLToPath(new URL('celular.png',out)),fullPage:true});
  await page.setViewportSize({width:1366,height:900});
  for(let i=0;i<6;i++) await page.evaluate(i=>goToStep(i),i);
  assert.deepEqual(errors,[]);
  console.log('OK: navegação, validação, download real, importação nos dois sentidos, recuperação local, logotipo, layout móvel e seis etapas sem erros.');
} finally {await browser.close();}
